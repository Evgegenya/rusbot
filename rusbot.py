def send_question(c, uid):
    sess = sessions.get(uid)
    if not sess or sess['i'] >= len(sess['words']):
        finish_practice(c, uid); return
    
    word_key, data = sess['words'][sess['i']]
    display = data.get('display', word_key)
    txt = f"📝 **Вопрос {sess['i']+1} из {len(sess['words'])}**\n\n💡 Заглавная = ударение!\n\n🔤 {display.upper()}\n\n{data.get('note', '')}"
    bot.edit_message_text(txt, c.message.chat.id, c.message.message_id, parse_mode='Markdown', reply_markup=answer_kb(word_key, data))

def finish_practice(c, uid):
    sess = sessions.pop(uid, {})
    total = sess.get('i', 0)
    bot.edit_message_text(f"🎉 **Тренировка завершена!**\n\nВопросов: {total}\n\nПродолжайте практиковаться!", c.message.chat.id, c.message.message_id, parse_mode='Markdown', reply_markup=main_kb())

