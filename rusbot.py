def db_init():
    conn = sqlite3.connect('ege.db')
    c = conn.cursor()
    c.execute('CREATE TABLE IF NOT EXISTS stats (user_id INTEGER PRIMARY KEY, total INT DEFAULT 0, correct INT DEFAULT 0)')
    c.execute('CREATE TABLE IF NOT EXISTS hard (user_id INTEGER, word TEXT, PRIMARY KEY (user_id, word))')
    conn.commit()
    conn.close()

def db_add_user(uid):
    conn = sqlite3.connect('ege.db')
    conn.execute('INSERT OR IGNORE INTO stats (user_id) VALUES (?)', (uid,))
    conn.commit()
    conn.close()

def db_update(uid, ok):
    conn = sqlite3.connect('ege.db')
    if ok:
        conn.execute('UPDATE stats SET total=total+1, correct=correct+1 WHERE user_id=?', (uid,))
    else:
        conn.execute('UPDATE stats SET total=total+1 WHERE user_id=?', (uid,))
    conn.commit()
    conn.close()

def db_get_stats(uid):
    conn = sqlite3.connect('ege.db')
    r = conn.execute('SELECT total, correct FROM stats WHERE user_id=?', (uid,)).fetchone()
    conn.close()
    return r if r else (0, 0)

def db_add_hard(uid, word):
    conn = sqlite3.connect('ege.db')
    conn.execute('INSERT OR IGNORE INTO hard VALUES (?, ?)', (uid, word))
    conn.commit()
    conn.close()

def db_get_hard(uid):
    conn = sqlite3.connect('ege.db')
    words = [r[0] for r in conn.execute('SELECT word FROM hard WHERE user_id=?', (uid,))]
    conn.close()
    return words

